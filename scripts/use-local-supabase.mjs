import { execSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const envPath = path.join(root, ".env.local");
const backupPath = path.join(root, ".env.local.before-local");

function unquote(value) {
  const v = value.trim();
  if (
    (v.startsWith('"') && v.endsWith('"')) ||
    (v.startsWith("'") && v.endsWith("'"))
  ) {
    return v.slice(1, -1);
  }
  return v;
}

let output;
try {
  output = execSync("npx supabase status -o env", {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
} catch (error) {
  const detail = error.stderr?.toString().trim();
  console.error(
    "Impossible de lire le statut Supabase local. Lancez `npx supabase start` d'abord.",
  );
  if (detail) console.error(detail);
  process.exit(1);
}

const status = {};
for (const raw of output.split(/\r?\n/)) {
  const match = /^([A-Z0-9_]+)=(.*)$/.exec(raw.trim());
  if (match) status[match[1]] = unquote(match[2]);
}

const apiUrl = status.API_URL;
const anonKey = status.ANON_KEY ?? status.PUBLISHABLE_KEY;
const serviceKey = status.SERVICE_ROLE_KEY ?? status.SECRET_KEY;

if (!apiUrl || !anonKey || !serviceKey) {
  console.error("Statut Supabase incomplet : API_URL, ANON_KEY ou SERVICE_ROLE_KEY absent.");
  process.exit(1);
}

const existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, "utf8") : "";
const tokenMatch = /^TOKEN_ENCRYPTION_KEY=(.*)$/m.exec(existing);
const tokenKey =
  tokenMatch?.[1]?.trim() ||
  crypto.randomBytes(32).toString("base64");

if (existing) fs.writeFileSync(backupPath, existing);

const content = [
  "# Local Supabase (generated by npm run db:local-env)",
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `SUPABASE_ANON_KEY=${anonKey}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
  `TOKEN_ENCRYPTION_KEY=${tokenKey}`,
  "TRUST_PROXY=0",
  "",
].join("\n");

fs.writeFileSync(envPath, content);

console.log(`.env.local pointe maintenant vers ${apiUrl}`);
console.log(`Sauvegarde de l'ancien fichier : ${backupPath}`);
console.log("Redémarrez `npm run dev` pour charger les nouvelles variables.");
